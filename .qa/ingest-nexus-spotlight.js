/* Appends verified Week 46 resources to the canonical registries and writes
   the Nexus Spotlight editorial layer. Idempotent: existing IDs are skipped. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const additions = JSON.parse(fs.readFileSync(path.join(__dirname, 'nexus-additions.json'), 'utf8'));
const VERIFIED_ON = additions.lastReviewed || '2026-11-14';

const load = (file, key) => {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(path.join(root, 'data', file), 'utf8'), sandbox, { filename: file });
  return sandbox.window[key];
};

const models = load('ai-models.js', 'AI_MODELS');
const tools = load('ai-tools.js', 'AI_TOOLS');
const modelMeta = load('ai-models.js', 'AI_MODELS_META');
const toolMeta = load('ai-tools.js', 'AI_TOOLS_META');

const fail = (message) => { throw new Error(message); };
const seenModelIds = new Set(models.map((r) => r.id));
const seenModelNames = new Set(models.map((r) => r.name.toLowerCase()));
const seenToolIds = new Set(tools.map((r) => r.id));
const seenToolNames = new Set(tools.map((r) => r.name.toLowerCase()));

for (const record of additions.models) {
  if (!record.id || !record.name) fail('model record missing id/name');
  if (seenModelIds.has(record.id)) fail('duplicate model id in additions: ' + record.id);
  if (seenModelNames.has(record.name.toLowerCase())) fail('duplicate model name in additions: ' + record.name);
  seenModelIds.add(record.id);
  seenModelNames.add(record.name.toLowerCase());
}
for (const record of additions.tools) {
  if (!record.id || !record.name) fail('tool record missing id/name');
  if (seenToolIds.has(record.id)) fail('duplicate tool id in additions: ' + record.id);
  if (seenToolNames.has(record.name.toLowerCase())) fail('duplicate tool name in additions: ' + record.name);
  seenToolIds.add(record.id);
  seenToolNames.add(record.name.toLowerCase());
}

const existingModelIds = new Set(models.map((r) => r.id));
const existingToolIds = new Set(tools.map((r) => r.id));
const appendedModels = additions.models.filter((r) => !existingModelIds.has(r.id));
const appendedTools = additions.tools.filter((r) => !existingToolIds.has(r.id));

const nextModels = models.concat(appendedModels);
const nextTools = tools.concat(appendedTools);

const rebuildMeta = (meta, records, extra) => {
  const counts = {};
  records.forEach((r) => { counts[r.category] = (counts[r.category] || 0) + 1; });
  const order = Array.isArray(meta.category_order) ? meta.category_order.slice() : [];
  records.forEach((r) => { if (!order.includes(r.category)) order.push(r.category); });
  return {
    ...meta,
    ...extra,
    category_order: order,
    categories: order.filter((c) => counts[c]).map((name) => ({ name, count: counts[name] }))
  };
};

const nextModelMeta = rebuildMeta(modelMeta, nextModels, {
  count: nextModels.length,
  last_verified: VERIFIED_ON,
  source_records: nextModels.length
});
const nextToolMeta = rebuildMeta(toolMeta, nextTools, {
  count: nextTools.length,
  last_verified: VERIFIED_ON,
  source_records: nextTools.length - (toolMeta.merged_legacy || 0)
});

const writeDataModule = (file, varName, metaName, records, meta) => {
  const body = records.map((r) => JSON.stringify(r)).join(',\n');
  const text = `/* Generated by .qa/import-build.js from the uploaded registry files.
   Do not edit by hand; re-run the importer instead. */
window.${varName} = [
${body}
];
window.${metaName} = ${JSON.stringify(meta, null, 2)};
`;
  fs.writeFileSync(path.join(root, 'data', file), text, 'utf8');
};

if (appendedModels.length) writeDataModule('ai-models.js', 'AI_MODELS', 'AI_MODELS_META', nextModels, nextModelMeta);
if (appendedTools.length) writeDataModule('ai-tools.js', 'AI_TOOLS', 'AI_TOOLS_META', nextTools, nextToolMeta);

/* Root source snapshots: append the same records so the JSON mirrors stay in step. */
const appendRootModels = () => {
  const file = path.join(root, 'ai-models.json');
  const json = JSON.parse(fs.readFileSync(file, 'utf8'));
  const ids = new Set(json.map((r) => r.canonical_id));
  let nextId = Math.max(...json.map((r) => Number(r.id) || 0)) + 1;
  additions.models.forEach((r) => {
    if (ids.has(r.canonical_id)) return;
    json.push({
      id: nextId++,
      name: r.name,
      icon: null,
      domain: r.domain,
      category: r.source_category,
      resource_type: 'model',
      subtype: r.source_category,
      description: r.description,
      pricing: r.pricing,
      signup_required: r.signup_required ? 'Yes' : 'No',
      local_execution: r.local_execution,
      technical_tags: r.tags,
      params: r.params,
      context: r.context,
      context_k: r.context_k,
      license: r.license,
      license_group: r.license_group,
      moe: r.moe,
      verified_link: { title: 'Official source', url: r.official_url },
      canonical_id: r.canonical_id,
      verification_status: 'verified',
      evidence_sources: r.evidence.map((e) => e[1]),
      last_verified: r.verified,
      notes: r.notes
    });
    ids.add(r.canonical_id);
  });
  fs.writeFileSync(file, JSON.stringify(json, null, 1) + '\n', 'utf8');
};

const appendRootCombined = () => {
  const file = path.join(root, 'ai-resources-1000.json');
  const json = JSON.parse(fs.readFileSync(file, 'utf8'));
  const ids = new Set(json.map((r) => r.canonical_id));
  let nextId = Math.max(...json.map((r) => Number(r.id) || 0)) + 1;
  const push = (r, type) => {
    if (ids.has(r.canonical_id)) return;
    json.push({
      id: nextId++,
      name: r.name,
      icon: null,
      domain: r.domain,
      category: r.source_category,
      resource_type: type,
      subtype: r.source_category,
      description: r.description,
      pricing: r.pricing,
      signup_required: r.signup_required ? 'Yes' : 'No',
      local_execution: r.local_execution,
      technical_tags: r.tags,
      verified_link: { title: 'Official source', url: r.official_url },
      canonical_id: r.canonical_id,
      verification_status: 'verified',
      evidence_sources: r.evidence.map((e) => e[1]),
      last_verified: r.verified,
      notes: r.notes
    });
    ids.add(r.canonical_id);
  };
  additions.models.forEach((r) => push(r, 'model'));
  additions.tools.forEach((r) => push(r, 'tool'));
  fs.writeFileSync(file, JSON.stringify(json, null, 1) + '\n', 'utf8');
};

appendRootModels();
appendRootCombined();

/* Editorial layer: one record per spotlight item, resolved against the registries. */
const modelIndex = new Map(nextModels.map((r) => [r.id, r]));
const toolIndex = new Map(nextTools.map((r) => [r.id, r]));
const resolve = (item) => {
  if (item.type === 'model') return modelIndex.get(item.id);
  if (item.type === 'tool') return toolIndex.get(item.id);
  return null;
};

const registryFor = (type) => (type === 'model' ? 'AI Models' : 'AI Tools');
const pageFor = (type) => (type === 'model' ? 'models.html' : 'ai-tools.html');
const routeFor = (type) => (type === 'model' ? 'model' : 'tool');
const typeLabel = (type) => (type === 'model' ? 'Model' : 'Tool');

const items = additions.spotlight.map((item) => {
  const record = resolve(item);
  if (!record) fail('spotlight item does not resolve: ' + item.type + ':' + item.id);
  return {
    type: item.type,
    id: item.id,
    name: record.name,
    badge: item.badge,
    released: item.released,
    category: record.category,
    registry: registryFor(item.type),
    typeLabel: typeLabel(item.type),
    description: record.description,
    officialUrl: record.official_url,
    detailPath: `${pageFor(item.type)}#${routeFor(item.type)}/${encodeURIComponent(record.id)}`,
    firstSeen: item.released,
    lastReviewed: additions.lastReviewed
  };
});

const moduleText = `/* Nexus Spotlight editorial layer.
   Members are stable type/id references into the canonical registries.
   This file is not a registry and contains no duplicated canonical records. */
window.DSH_NEXUS_SPOTLIGHT = {
  id: 'nexus-spotlight',
  eyebrow: 'NEXUS SPOTLIGHT',
  title: "Discover What's Worth Exploring",
  description: 'Explore noteworthy AI tools, models, and developer resources selected for their relevance, practical value, and potential impact on modern technology workflows.',
  supporting: 'From newly released AI models to useful developer platforms, Nexus Spotlight brings noteworthy discoveries together and connects them to the broader DevSpire Nexus resource ecosystem.',
  lastReviewed: '${additions.lastReviewed}',
  items: ${JSON.stringify(items, null, 2)}
};
`;
fs.writeFileSync(path.join(root, 'data', 'nexus-spotlight.js'), moduleText, 'utf8');

console.log(`models: ${models.length} -> ${nextModels.length} (+${appendedModels.length})`);
console.log(`tools: ${tools.length} -> ${nextTools.length} (+${appendedTools.length})`);
console.log(`spotlight items: ${items.length}`);
console.log('spotlight types:', items.reduce((acc, i) => { acc[i.type] = (acc[i.type] || 0) + 1; return acc; }, {}));
