/* Regenerates data/related-index.js from the three canonical registries using
   the same row schema as .qa/import-build.js. Idempotent. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const load = (file, key) => {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(path.join(root, 'data', file), 'utf8'), sandbox, { filename: file });
  return sandbox.window[key];
};

const registries = {
  t: load('ai-tools.js', 'AI_TOOLS'),
  m: load('ai-models.js', 'AI_MODELS'),
  d: load('developer-resources.js', 'DEVELOPER_RESOURCES')
};

const shortDesc = (value) => {
  const clean = String(value || '').replace(/\s+/g, ' ').trim();
  if (clean.length <= 180) return clean;
  const cut = clean.slice(0, 180);
  return cut.slice(0, cut.lastIndexOf(' ')) + '…';
};

const rootDomain = (url) => {
  try {
    const parts = new URL(url).hostname.split('.');
    return parts.length > 2 ? parts.slice(-2).join('.') : parts.join('.');
  } catch {
    return '';
  }
};

const relatedRow = (r) => [
  r.id,
  r.name,
  r.category,
  r.source_category || r.family || r.resource_subtype || '',
  r.provider || rootDomain(r.official_url),
  r.icon || null,
  shortDesc(r.description),
  (r.tags || []).slice(0, 8),
  r.official_url
];

const index = {
  v: 1,
  generated: new Date().toISOString(),
  t: registries.t.map(relatedRow),
  m: registries.m.map(relatedRow),
  d: registries.d.map(relatedRow)
};

fs.writeFileSync(
  path.join(root, 'data', 'related-index.js'),
  `/* Generated by .qa/import-build.js. Compact cross-registry relationship index. */\nwindow.RELATED_INDEX = ${JSON.stringify(index)};\n`,
  'utf8'
);
console.log(`related-index.js: ${index.t.length} tools, ${index.m.length} models, ${index.d.length} developer resources`);
