const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const { models, icons } = JSON.parse(fs.readFileSync(path.join(__dirname, 'model-records.json'), 'utf8'));

const SOURCE = 'https://github.com/kumaradoss16/ai-knowledge-base/blob/main/ai-tools/ai-tools-models-developer-resources.md';
const VERIFIED = '2026-11-03';
const CATEGORY_ORDER = [
  'Large Language Models',
  'Reasoning & CoT',
  'Coding Models',
  'Vision & Multimodal',
  'Image Generation',
  'Audio & Speech',
  'Video Generation',
  'Embeddings & Rerankers',
  'Small / Edge Models'
];

const seen = new Set();
const records = models.map((m) => {
  if (seen.has(m.id)) throw new Error('duplicate id: ' + m.id);
  seen.add(m.id);
  if (!CATEGORY_ORDER.includes(m.cat)) throw new Error('unexpected category: ' + m.id + ' / ' + m.cat);
  if (!/^https:\/\//.test(m.url)) throw new Error('non-https url: ' + m.id);
  if (!['open', 'closed'].includes(m.weights)) throw new Error('unexpected weights: ' + m.id);
  if (!['usage_based', 'open_weights', 'open_source'].includes(m.pricing)) throw new Error('unexpected pricing: ' + m.id);
  const icon = icons[m.icon] || null;
  if (icon && !fs.existsSync(path.join(root, icon))) throw new Error('missing icon: ' + icon);

  return {
    id: m.id,
    name: m.name,
    publisher: m.publisher,
    description: m.desc,
    category: m.cat,
    source_category: m.sub,
    family: m.family,
    resource_type: 'AI Model',
    official_url: m.url,
    pricing: m.pricing,
    weights: m.weights,
    open_weights: m.weights === 'open',
    self_hostable: !!m.local,
    signup_required: !!m.signup,
    license: m.license,
    license_group: m.licenseGroup,
    params: m.params,
    context_k: m.contextK,
    moe: !!m.moe,
    modalities: m.modalities,
    tags: m.tags,
    icon,
    verified: m.verified,
    status: 'verified',
    evidence: m.evidence,
    source: SOURCE
  };
});

records.forEach((r) => {
  if (!r.tags.length) throw new Error('no tags: ' + r.id);
  if (!r.modalities.length) throw new Error('no modalities: ' + r.id);
  if (!r.evidence.length) throw new Error('no evidence: ' + r.id);
  if (r.evidence.some(([label, url]) => !label || !/^https:\/\//.test(url))) throw new Error('bad evidence: ' + r.id);
});

const categories = CATEGORY_ORDER
  .filter((c) => records.some((r) => r.category === c))
  .map((c) => ({ name: c, count: records.filter((r) => r.category === c).length }));

const meta = {
  count: records.length,
  catalog: 'ai-models',
  source: SOURCE,
  last_verified: VERIFIED,
  categories
};

const header = `/* AI Models registry — generated by .qa/models-build.js.
   Provenance: every record was extracted from kumaradoss16/ai-knowledge-base ·
   ai-tools/ai-tools-models-developer-resources.md (Resource Type: model) on
   ${VERIFIED}. The upstream repository is no longer publicly reachable, so the
   extraction persisted in models.html is the retained copy of that source.
   params and context_k stay null where the source states no figure — never
   estimated. Presentation code lives in models.html; do not edit by hand. */
`;

const body = header +
  'window.AI_MODELS = ' + JSON.stringify(records, null, 2) + ';\n\n' +
  'window.AI_MODELS_META = ' + JSON.stringify(meta, null, 2) + ';\n';

fs.writeFileSync(path.join(root, 'data', 'ai-models.js'), body);

console.log('written data/ai-models.js:', body.length, 'bytes');
console.log('records:', records.length);
console.log('categories:', JSON.stringify(categories));
console.log('with icon:', records.filter((r) => r.icon).length, '| chip fallback:', records.filter((r) => !r.icon).map((r) => r.name));
console.log('open weights:', records.filter((r) => r.open_weights).length, '| self-hostable:', records.filter((r) => r.self_hostable).length);
console.log('params stated:', records.filter((r) => r.params).length, '| context stated:', records.filter((r) => r.context_k !== null).length);
