const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const { tools, icons } = JSON.parse(fs.readFileSync(path.join(__dirname, 'tool-records.json'), 'utf8'));

const SOURCE = 'https://github.com/kumaradoss16/ai-knowledge-base/blob/main/ai-tools/ai-tools-models-developer-resources.md';
const VERIFIED = '2026-11-04';

const CATEGORY_ORDER = [
  'Assistants & Chatbots',
  'Search & Research',
  'Coding & Development',
  'Writing & Content',
  'Productivity',
  'Automation & Workflows',
  'AI Agents',
  'Image Generation',
  'Video Generation',
  'Audio & Voice',
  'Design & Creative',
  'Data & Docs'
];

const slug = (s) => s.toLowerCase()
  .replace(/&/g, ' and ')
  .replace(/\+/g, ' plus ')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');

const HOSTING = {
  'Cloud-hosted': 'Managed Cloud',
  'Local execution': 'Local',
  'Self-hostable': 'Self-hosted'
};

const sourceTools = tools.filter((t) => t.sub);
if (!sourceTools.length) throw new Error('no source tool records found');

const seen = new Set();
const records = sourceTools.map((t) => {
  const id = slug(t.name);
  if (seen.has(id)) throw new Error('duplicate id: ' + id);
  seen.add(id);
  if (!CATEGORY_ORDER.includes(t.category)) throw new Error('unexpected category: ' + t.name + ' / ' + t.category);
  if (!/^https:\/\//.test(t.url)) throw new Error('non-https url: ' + t.name);

  const icon = icons[t.name] || null;
  if (icon && !fs.existsSync(path.join(root, icon))) throw new Error('missing icon file: ' + icon);

  const hosting = t.deployment.map((d) => {
    if (!HOSTING[d]) throw new Error('unexpected deployment: ' + t.name + ' / ' + d);
    return HOSTING[d];
  });
  const noSignup = t.access.includes('No signup required');

  return {
    id,
    name: t.name,
    org: t.org,
    description: t.desc,
    category: t.category,
    source_category: t.sub,
    resource_type: 'AI Tool',
    official_url: t.url,
    pricing: t.pricing,
    pricing_class: t.pricing === 'Freemium' ? 'freemium' : t.pricing === 'Paid' ? 'paid' : 'free',
    license: t.license,
    open_source: t.license === 'Open Source',
    platform: t.platform || null,
    hosting,
    self_hostable: t.deployment.includes('Self-hostable'),
    signup_required: noSignup ? false : null,
    tags: t.tags,
    initials: t.initials,
    icon,
    verified: VERIFIED,
    status: 'verified',
    notes: null,
    evidence: [['Verified link', t.url]],
    source: SOURCE
  };
});

/* Validations */
records.forEach((r) => {
  if (!r.tags.length) throw new Error('no tags: ' + r.name);
  if (r.platform && !['Web', 'Desktop', 'Multiple'].includes(r.platform)) throw new Error('unexpected platform: ' + r.name + ' / ' + r.platform);
  if (!['freemium', 'paid', 'free'].includes(r.pricing_class)) throw new Error('unexpected pricing: ' + r.name);
});

const categories = CATEGORY_ORDER
  .filter((c) => records.some((r) => r.category === c))
  .map((c) => ({ name: c, count: records.filter((r) => r.category === c).length }));

const meta = {
  count: records.length,
  catalog: 'ai-tools',
  source: SOURCE,
  last_verified: VERIFIED,
  categories
};

const header = `/* AI Tools registry — generated by .qa/tools-build.js.
   Provenance: every record was extracted from kumaradoss16/ai-knowledge-base ·
   ai-tools/ai-tools-models-developer-resources.md (Resource Type: tool) on
   ${VERIFIED}. The upstream repository is no longer publicly reachable, so the
   extraction persisted in tools.html is the retained copy of that source.
   Presentation code lives in ai-tools.html; do not edit records by hand. */
`;

const body = header +
  'window.AI_TOOLS = ' + JSON.stringify(records, null, 2) + ';\n\n' +
  'window.AI_TOOLS_META = ' + JSON.stringify(meta, null, 2) + ';\n';

fs.writeFileSync(path.join(root, 'data', 'ai-tools.js'), body);

const counts = {};
records.forEach((r) => { counts[r.category] = (counts[r.category] || 0) + 1; });
console.log('written data/ai-tools.js:', body.length, 'bytes');
console.log('records:', records.length);
console.log('categories:', JSON.stringify(counts, null, 2));
console.log('with icon:', records.filter((r) => r.icon).length, '| monogram fallback:', records.filter((r) => !r.icon).map((r) => r.name));
console.log('pricing:', JSON.stringify(records.reduce((m, r) => (m[r.pricing] = (m[r.pricing] || 0) + 1, m), {})));
console.log('self-hostable:', records.filter((r) => r.self_hostable).map((r) => r.name));
console.log('no signup:', records.filter((r) => r.signup_required === false).map((r) => r.name));
console.log('platform stated:', records.filter((r) => r.platform).map((r) => r.name + '=' + r.platform));
